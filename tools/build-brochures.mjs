/**
 * Builds the Arabic and Farsi flipbook editions from the English master.
 *
 *   node tools/build-brochures.mjs
 *
 * Master:        public/brochure/partner-catalogue-en.html
 * Translations:  src/brochure-i18n/{ar,fa}.json  (key = exact English text node)
 * Output:        public/brochure/partner-catalogue-{ar,fa}.html
 *
 * RTL editions: dir="rtl", Arabic/Farsi fonts, pages reversed so the book opens and turns right-to-left.
 * Re-run after editing the English master or a translation file.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MASTER = join(ROOT, 'public/brochure/partner-catalogue-en.html');

const FONTS = {
  ar: { family: 'Cairo', css: 'family=Cairo:wght@400;500;600;700;800' },
  fa: { family: 'Vazirmatn', css: 'family=Vazirmatn:wght@400;500;600;700;800' },
};

const unescape = (s) => s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");
const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const RTL_CSS = (font) => `
<style id="rtl-edition">
/* RTL edition overrides (generated by tools/build-brochures.mjs) */
:root{--f-body:"${font}","Wix Madefor Display",sans-serif;--f-display:"${font}","Plus Jakarta Sans",sans-serif;--f-mono:"${font}","Montserrat",sans-serif}
[dir=rtl] *{letter-spacing:0!important;text-transform:none!important}
[dir=rtl] body{line-height:1.7}
[dir=rtl] .note{border-left:0;border-right:3px solid var(--gold);padding:.2em .9em .2em 0}
[dir=rtl] ul.ticks li{padding-left:0;padding-right:1.3em}
[dir=rtl] ul.ticks li::before{left:auto;right:0}
[dir=rtl] .link{margin-left:0;margin-right:1.6em;border-left:0;border-right:2px dashed var(--ink-mute);padding-left:0;padding-right:.8em}
[dir=rtl] table th,[dir=rtl] table td,[dir=rtl] table caption{text-align:right}
[dir=rtl] table th:last-child,[dir=rtl] table td:last-child,[dir=rtl] .prow .tiers{text-align:left}
/* Keep Latin numbers, prize lists and ranges in reading order (brand rule: numbers in LTR) */
[dir=rtl] #count,[dir=rtl] .prow .tiers,[dir=rtl] table.lev td,[dir=rtl] table.rw td{direction:ltr;unicode-bidi:isolate}
[dir=rtl] table.lev td:first-child,[dir=rtl] table.rw td:first-child{text-align:right}
</style>`;

function translateBody(body, dict) {
  // Leave <script>/<style> untouched; translate visible text nodes only.
  return body
    .split(/(<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>)/)
    .map((part) =>
      /^<(script|style)/.test(part)
        ? part
        : part.replace(/>([^<]+)</g, (m, text) => {
            const key = unescape(text.trim());
            if (!key || !(key in dict)) return m;
            const lead = text.match(/^\s*/)[0];
            const trail = text.match(/\s*$/)[0];
            return `>${lead}${escape(dict[key])}${trail}<`;
          }),
    )
    .join('');
}

function reversePages(html) {
  // Reverse the <section class="pg ..."> order inside #book and swap left/right page classes.
  const start = html.indexOf('<section class="pg');
  const end = html.lastIndexOf('</section>') + '</section>'.length;
  const pages = html.slice(start, end).match(/<section class="pg[\s\S]*?<\/section>/g);
  const total = pages.length;
  const swapped = pages
    .reverse()
    .map((p) => p.replace(/^<section class="pg([^"]*)"/, (m, cls) => `<section class="pg${cls.replace(/\bleft\b/, '__R').replace(/\bright\b/, 'left').replace('__R', 'right')}"`));
  let out = html.slice(0, start) + swapped.join('\n') + html.slice(end);
  // Contents links point at page indexes: mirror them.
  out = out.replace(/data-go="(\d+)"/g, (m, n) => `data-go="${total - 1 - Number(n)}"`);
  return { html: out, total };
}

function rtlScript(html, total) {
  // Book starts on the last index (the cover), "Next" turns towards lower indexes, counter shows reading order.
  return html
    .replace('startPage:0', `startPage:${total - 1}`)
    .replace(
      'function update(i){',
      'function update(i){i=total-1-i;',
    )
    .replace('  update(0);', '  update(pf.getCurrentPageIndex());')
    .replace("prev.addEventListener('click',function(){pf.flipPrev()});", "prev.addEventListener('click',function(){pf.flipNext()});")
    .replace("next.addEventListener('click',function(){pf.flipNext()});", "next.addEventListener('click',function(){pf.flipPrev()});")
;
}

const master = readFileSync(MASTER, 'utf8');

for (const lang of ['ar', 'fa']) {
  const dict = JSON.parse(readFileSync(join(ROOT, `src/brochure-i18n/${lang}.json`), 'utf8'));
  const bodyAt = master.indexOf('<body');
  let head = master.slice(0, bodyAt);
  let body = translateBody(master.slice(bodyAt), dict);

  head = head
    .replace('<html lang="en">', `<html lang="${lang}" dir="rtl">`)
    .replace(/<title>[^<]*<\/title>/, `<title>${escape(dict._meta_title)}</title>`)
    .replace(/(<meta name="description" content=")[^"]*"/, `$1${escape(dict._meta_desc)}"`)
    .replace(/(<meta property="og:title" content=")[^"]*"/, `$1${escape(dict._meta_title)}"`)
    .replace('display=swap">', `display=swap">\n<link rel="stylesheet" href="https://fonts.googleapis.com/css2?${FONTS[lang].css}&display=swap">`)
    .replace('</head>', `${RTL_CSS(FONTS[lang].family)}\n</head>`);

  body = body
    .replace(/aria-label="Contents"/g, `aria-label="${dict._aria_contents}"`)
    .replace(/aria-label="Page controls"/g, `aria-label="${dict._aria_controls}"`)
    .replace(/aria-label="Previous page"/g, `aria-label="${dict._aria_prev}"`)
    .replace(/aria-label="Next page"/g, `aria-label="${dict._aria_next}"`);

  const { html, total } = reversePages(head + body);
  const out = rtlScript(html, total);
  writeFileSync(join(ROOT, `public/brochure/partner-catalogue-${lang}.html`), out);

  const missing = [...new Set([...body.matchAll(/>([^<]*[A-Za-z]{4,}[^<]*)</g)].map((m) => m[1].trim()))]
    .filter((t) => t && !/wegolden|WeGolden|MetaTrader|MT5|Standard|ECN|USDCHF|XAUUSD|US30|USDT|FSP|MSB|FAIS|MISA|FSCA|FinCEN|Cent|IB|MIB|HT\d|BFX/.test(t));
  console.log(`✔ ${lang}: ${total} pages → public/brochure/partner-catalogue-${lang}.html${missing.length ? `  (untranslated: ${missing.slice(0, 5).join(' | ')})` : ''}`);
}
